/**
 * Escape HTML entities to prevent HTML/SMTP injection.
 * Call this on ANY user-supplied string before interpolating into HTML.
 */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;')
}
